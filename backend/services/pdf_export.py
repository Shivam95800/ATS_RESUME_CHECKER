import io
import re
import logging
from typing import Dict

logger = logging.getLogger('ats_resume_scorer')

try:
    from weasyprint import HTML, CSS
    WEASYPRINT_INSTALLED = True
except (ImportError, OSError):
    WEASYPRINT_INSTALLED = False

try:
    from reportlab.lib.pagesizes import letter
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib import colors
    REPORTLAB_INSTALLED = True
except (ImportError, OSError):
    REPORTLAB_INSTALLED = False


def _generate_reportlab_pdf(html_docs: Dict[str, str]) -> bytes:
    """Fallback PDF generator using ReportLab when WeasyPrint system C-libraries are missing."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Title'],
        fontName='Helvetica-Bold',
        fontSize=18,
        leading=22,
        textColor=colors.HexColor('#0f172a'),
        alignment=0,
        spaceAfter=8
    )
    h2_style = ParagraphStyle(
        'DocH2',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=12,
        leading=15,
        textColor=colors.HexColor('#1e293b'),
        spaceBefore=10,
        spaceAfter=4
    )
    body_style = ParagraphStyle(
        'DocBody',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#334155'),
        spaceAfter=4
    )
    bullet_style = ParagraphStyle(
        'DocBullet',
        parent=body_style,
        leftIndent=15,
        firstLineIndent=-10,
        spaceAfter=3
    )

    story = [
        Paragraph('ATS Resume Scorer — Detailed Analysis Report', title_style),
        HRFlowable(width='100%', thickness=1.5, color=colors.HexColor('#3b82f6'), spaceBefore=2, spaceAfter=8)
    ]

    section_titles = {
        'summary': '1. Executive Summary & Component Breakdown',
        'skill_report': '2. Skill Validation & Content Analysis',
        'jd_report': '3. Job Description Match Analysis',
        'recommendations': '4. Action Items & Improvement Recommendations'
    }

    for key, html_str in html_docs.items():
        sec_title = section_titles.get(key, key.replace('_', ' ').title())
        story.append(Paragraph(sec_title, h2_style))
        story.append(HRFlowable(width='100%', thickness=0.5, color=colors.HexColor('#cbd5e1'), spaceBefore=2, spaceAfter=6))

        clean_html = re.sub(r'(?is)<style.*?>.*?</style>', '', html_str)
        clean_html = re.sub(r'(?is)<script.*?>.*?</script>', '', clean_html)
        elements = re.findall(
            r'(<(?:h[1-6]|p|li|div)[^>]*>(.*?)</(?:h[1-6]|p|li|div)>)',
            clean_html,
            re.IGNORECASE | re.DOTALL
        )

        added_lines = 0
        for full_tag, inner in elements:
            text_content = re.sub(r'<[^>]+>', ' ', inner).strip()
            text_content = re.sub(r'\s+', ' ', text_content)
            # Escape XML entities for ReportLab
            text_content = text_content.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')

            if not text_content or len(text_content) < 3:
                continue

            if any(bp in text_content.lower() for bp in ('generated by ats', 'report 1 of', 'report 2 of', 'report 3 of', 'report 4 of')):
                continue

            tag_lower = full_tag.lower()
            if '<li' in tag_lower:
                safe_text = f"• {text_content[:250]}"
                story.append(Paragraph(safe_text, bullet_style))
            elif any(h in tag_lower for h in ('<h1', '<h2', '<h3')):
                story.append(Paragraph(text_content[:150], h2_style))
            else:
                story.append(Paragraph(text_content[:300], body_style))

            added_lines += 1
            if added_lines >= 40:
                break

        story.append(Spacer(1, 8))

    doc.build(story)
    return buffer.getvalue()


def generate_combined_pdf(html_docs: Dict[str, str]) -> bytes:
    if WEASYPRINT_INSTALLED:
        try:
            documents = []
            for name, html_str in html_docs.items():
                doc = HTML(string=html_str).render()
                documents.append(doc)

            first_doc = documents[0]
            for other_doc in documents[1:]:
                for page in other_doc.pages:
                    first_doc.pages.append(page)

            return first_doc.write_pdf()
        except Exception as exc:
            logger.warning(f"WeasyPrint rendering failed ({exc}), attempting ReportLab fallback...")

    if REPORTLAB_INSTALLED:
        return _generate_reportlab_pdf(html_docs)

    raise ImportError("Neither WeasyPrint nor ReportLab is available for PDF generation.")
